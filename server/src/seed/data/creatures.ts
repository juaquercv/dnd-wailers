/** Fantasy bestiary followed by the steampunk one of "Los Cielos de Latón" (seed v2). */
const DEFS: CreatureDef[] = [...FANTASY_DEFS, ...STEAM_CREATURE_DEFS.map((d) => ({ ...d, origin: 'A' as const, since: 2 }))];

export { STEAM_CREATURE_KEYS };

export const CREATURE_ENTRIES: SeedEntry<'creature'>[] = DEFS.map((d) =>
  seedEntry<'creature'>({
    id: creatureId(d.key),
    kind: 'creature',
    name: d.name,
    description: d.description,
    imageUrl: seedUrl(portraitFile(d.portrait)),
    tags: d.tags,
    categoryIds: d.categories,
    origin: d.origin ?? null,
    since: d.since ?? 1,
    cr: d.cr,
    hp: d.hp,
    size: d.size,
    data: { ...emptyCreatureData(), ...d.data },
  }),
);

export function creatureEntry(key: string): SeedEntry<'creature'> {
  const found = CREATURE_ENTRIES.find((e) => e.id === creatureId(key));
  if (!found) throw new Error(`Criatura de semilla inexistente: ${key}`);
  return found;
}
